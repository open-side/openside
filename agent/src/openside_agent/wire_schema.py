"""JSON Schema of sidecar protocol v1, generated from the pydantic wire models.

    uv run --project agent python -m openside_agent.wire_schema \\
        > docs/specs/sidecar-wire.schema.json

The Python models are the generator; agent/tests/test_wire_schema.py fails when the
committed file drifts from them, and the Rust crate validates every message it emits
against it. docs/specs/sidecar-protocol.md stays normative for semantics.
"""

from __future__ import annotations

import json
from typing import Any

from pydantic import TypeAdapter

from openside_agent.protocol import Inbound, Outbound

PROTOCOL = 1
# Sidecar package versions the daemon accepts in `hello.versions.openside_agent`; equals
# openside_agent_sidecar::supported_agent_versions() (checked on both sides).
SUPPORTED_AGENT_VERSIONS = ">=0.1.0,<0.2.0"


def _require_constants(definition: dict[str, Any]) -> None:
    # Discriminators and the envelope `v` have defaults in Python, so pydantic marks
    # them optional; on the wire both sides always send them.
    properties: dict[str, Any] = definition.get("properties", {})
    constants = [name for name, value in properties.items() if "const" in value]
    if constants:
        required: list[str] = definition.setdefault("required", [])
        required.extend(name for name in constants if name not in required)


def schema() -> dict[str, Any]:
    by_key, definitions = TypeAdapter.json_schemas(
        [
            ("DaemonToSidecar", "validation", TypeAdapter(Inbound)),
            ("SidecarToDaemon", "validation", TypeAdapter(Outbound)),
        ]
    )
    defs: dict[str, Any] = dict(definitions.get("$defs", {}))
    for definition in defs.values():
        _require_constants(definition)
    for (name, _), value in by_key.items():
        defs[name] = value
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "openside sidecar wire protocol",
        "description": (
            "Generated by `python -m openside_agent.wire_schema` from "
            "agent/src/openside_agent/protocol.py. "
            "Semantics: docs/specs/sidecar-protocol.md."
        ),
        "x-protocol": PROTOCOL,
        "x-openside-agent-versions": SUPPORTED_AGENT_VERSIONS,
        "$defs": dict(sorted(defs.items())),
    }


def render() -> str:
    return json.dumps(schema(), indent=2, sort_keys=False) + "\n"


if __name__ == "__main__":
    print(render(), end="")
