#!/usr/bin/python3
"""Long-lived wlr virtual pointer for the headless sway QA desktop.

Headless sway has no input devices, so Chromium sees no pointer and toolbar/menu
clicks are impossible. This client keeps one virtual pointer alive (its seat keeps
the pointer capability) and reads `click X Y` / `move X Y` lines from a FIFO.
Runs with the system python inside the QA container (python-pywayland bindings in
/opt/wlproto, generated by tools/qa/headed-ux.Containerfile).

usage: wl_pointer.py FIFO OUTPUT_WIDTH OUTPUT_HEIGHT
"""

import os
import sys
import time

sys.path.insert(0, "/opt")
from pywayland.client import Display  # noqa: E402
from wlproto.wayland import WlSeat  # noqa: E402
from wlproto.wlr_virtual_pointer_unstable_v1 import ZwlrVirtualPointerManagerV1  # noqa: E402

BTN_LEFT = 0x110


def main() -> None:
    fifo, width, height = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    display = Display()
    display.connect()
    found: dict = {}

    def on_global(registry, name, interface, version):
        if interface == "wl_seat":
            found["seat"] = registry.bind(name, WlSeat, 1)
        elif interface == "zwlr_virtual_pointer_manager_v1":
            found["manager"] = registry.bind(name, ZwlrVirtualPointerManagerV1, 1)

    registry = display.get_registry()
    registry.dispatcher["global"] = on_global
    display.roundtrip()
    pointer = found["manager"].create_virtual_pointer(found["seat"])
    display.roundtrip()
    start = time.monotonic()

    def now() -> int:
        return int((time.monotonic() - start) * 1000)

    def button(state: int) -> None:
        pointer.button(now(), BTN_LEFT, state)
        pointer.frame()
        display.flush()

    print("ready", flush=True)
    # O_RDWR keeps a writer open on our side, so writers coming and going never cause EOF.
    with os.fdopen(os.open(fifo, os.O_RDWR), "r") as commands:
        for line in commands:
            verb, x, y = line.split()
            pointer.motion_absolute(now(), int(x), int(y), width, height)
            pointer.frame()
            display.flush()
            time.sleep(0.1)
            if verb == "click":
                button(1)
                time.sleep(0.05)
                button(0)
            display.roundtrip()


if __name__ == "__main__":
    main()
